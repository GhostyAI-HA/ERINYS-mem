#!/usr/bin/env python3
"""w3 ablation sweep: one ranking component removed at a time, all benches.

Design source: aionexo/paper/erinys/baseline_experiment_design.md §4 (private).
Modes are defined in each bench's SEARCH_FNS (ablate_* entries). Sequential
subprocess execution with per-config resume (skip when a summary exists),
streamed progress lines for external monitoring, and a final aggregation into
results/ablation/ablation.csv + ABLATION_RESULTS.md.

Usage:
  .venv/bin/python benchmarks/comparison/run_ablation.py [--limit N] [--only bench]
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import subprocess
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
PYTHON = str(REPO_ROOT / ".venv" / "bin" / "python")
ABLATION_DIR = REPO_ROOT / "benchmarks" / "comparison" / "results" / "ablation"

LME_DATA = "/tmp/longmemeval-data/longmemeval_s.json"
LOCOMO_DATA = "/tmp/locomo-data/locomo10.json"
CONVOMEM_CACHE = "/tmp/convomem_cache"

FULL_MODE = "enhanced_v2_boost"
COMMON_ABLATIONS = [
    "ablate_no_bigram",
    "ablate_no_keyword",
    "ablate_rrf_plain",
    "ablate_vec_only",
    "ablate_fts_only",
]

# (bench, mode, top_k). LongMemEval/LoCoMo report R@5+R@10 in one run;
# ConvoMem reports only R@top_k, so it runs at both cutoffs.
def build_plan() -> list[tuple[str, str, int]]:
    plan: list[tuple[str, str, int]] = []
    for mode in [FULL_MODE, *COMMON_ABLATIONS, "ablate_no_temporal"]:
        plan.append(("longmemeval", mode, 10))
    for mode in [FULL_MODE, *COMMON_ABLATIONS]:
        plan.append(("locomo", mode, 10))
    for top_k in (5, 10):
        for mode in [FULL_MODE, *COMMON_ABLATIONS]:
            plan.append(("convomem", mode, top_k))
    return plan


def config_dir(bench: str, mode: str, top_k: int, limit: int | None = None) -> Path:
    # Limited (smoke) runs live in *_smoke dirs so the resume skip-guard and
    # the aggregator never mistake them for full results.
    suffix = "_smoke" if limit else ""
    return ABLATION_DIR / f"{bench}_{mode}_k{top_k}{suffix}"


def existing_summary(out_dir: Path) -> Path | None:
    hits = sorted(glob.glob(str(out_dir / "summary_*.json")))
    return Path(hits[-1]) if hits else None


def build_command(bench: str, mode: str, top_k: int, out_dir: Path, limit: int | None) -> list[str]:
    if bench == "longmemeval":
        cmd = [PYTHON, "benchmarks/longmemeval_bench.py", LME_DATA]
    elif bench == "locomo":
        cmd = [PYTHON, "benchmarks/locomo_bench.py", LOCOMO_DATA]
    else:
        cmd = [PYTHON, "benchmarks/convomem_bench.py", "--cache-dir", CONVOMEM_CACHE]
    cmd += ["--mode", mode, "--top-k", str(top_k), "--no-progress", "--output", str(out_dir)]
    if limit:
        cmd += ["--limit", str(limit)]
    return cmd


def extract_metrics(summary: dict) -> dict[str, object]:
    overall = summary.get("overall", {})
    row = {
        "n": summary.get("total_questions", summary.get("total_items", "")),
        "r_at_5": overall.get("R@5", ""),
        "r_at_10": overall.get("R@10", ""),
        "ndcg_at_5": overall.get("NDCG@5", ""),
        "ndcg_at_10": overall.get("NDCG@10", ""),
    }
    if "R@k" in overall:  # convomem: single cutoff per run
        key = "r_at_5" if summary.get("top_k") == 5 else "r_at_10"
        row[key] = overall["R@k"]
    return row


def aggregate() -> tuple[list[dict[str, object]], Path, Path]:
    rows = []
    for path in sorted(ABLATION_DIR.glob("*/summary_*.json")):
        if path.parent.name.endswith("_smoke"):
            continue
        summary = json.loads(path.read_text(encoding="utf-8"))
        bench, rest = path.parent.name.split("_", 1)
        mode, k_tag = rest.rsplit("_k", 1)
        rows.append({
            "bench": bench,
            "mode": mode,
            "top_k": int(k_tag),
            **extract_metrics(summary),
            "summary_file": path.name,
        })
    csv_path = ABLATION_DIR / "ablation.csv"
    fields = ["bench", "mode", "top_k", "n", "r_at_5", "r_at_10",
              "ndcg_at_5", "ndcg_at_10", "summary_file"]
    import csv as _csv
    with csv_path.open("w", encoding="utf-8", newline="") as handle:
        writer = _csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)

    md_path = ABLATION_DIR / "ABLATION_RESULTS.md"
    lines = [
        "# w3 Ablation results",
        "",
        "Generated by run_ablation.py from summary JSONs. Do not hand-edit numbers.",
        "",
        "| Bench | Mode | n | R@5 | R@10 | NDCG@5 |",
        "|:--|:--|--:|--:|--:|--:|",
    ]
    merged: dict[tuple[str, str], dict[str, object]] = {}
    for row in rows:  # merge convomem k5/k10 runs into one display row
        key = (row["bench"], row["mode"])
        target = merged.setdefault(key, dict(row))
        for metric in ("r_at_5", "r_at_10", "ndcg_at_5", "ndcg_at_10"):
            if row[metric] != "":
                target[metric] = row[metric]
    for (bench, mode), row in sorted(merged.items()):
        def fmt(value: object) -> str:
            return f"{value:.1f}" if isinstance(value, (int, float)) else "-"
        ndcg = row["ndcg_at_5"]
        ndcg_s = f"{ndcg:.3f}" if isinstance(ndcg, (int, float)) else "-"
        lines.append(
            f"| {bench} | {mode} | {row['n']} | {fmt(row['r_at_5'])} | "
            f"{fmt(row['r_at_10'])} | {ndcg_s} |"
        )
    md_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return rows, csv_path, md_path


def main() -> int:
    parser = argparse.ArgumentParser(description="w3 ablation sweep")
    parser.add_argument("--limit", type=int, default=None,
                        help="per-bench question limit (smoke only)")
    parser.add_argument("--only", choices=["longmemeval", "locomo", "convomem"],
                        default=None)
    args = parser.parse_args()

    env = dict(os.environ)
    env.setdefault("FASTEMBED_CACHE_PATH", str(Path.home() / ".cache" / "fastembed"))
    env.setdefault("PYTHONWARNINGS", "ignore")

    plan = [p for p in build_plan() if not args.only or p[0] == args.only]
    failed: list[str] = []
    for index, (bench, mode, top_k) in enumerate(plan, 1):
        out_dir = config_dir(bench, mode, top_k, args.limit)
        label = f"{bench}/{mode}/k{top_k}"
        if existing_summary(out_dir) and not args.limit:
            print(f"[ablation] {index}/{len(plan)} {label} SKIP (summary exists)",
                  flush=True)
            continue
        out_dir.mkdir(parents=True, exist_ok=True)
        started = time.time()
        proc = subprocess.run(
            build_command(bench, mode, top_k, out_dir, args.limit),
            cwd=REPO_ROOT, env=env, capture_output=True, text=True,
        )
        elapsed = time.time() - started
        summary_path = existing_summary(out_dir)
        if proc.returncode != 0 or summary_path is None:
            failed.append(label)
            print(f"[ablation] {index}/{len(plan)} {label} FAILED rc={proc.returncode} "
                  f"({elapsed:.0f}s)", flush=True)
            tail = (proc.stderr or proc.stdout or "").strip().splitlines()[-8:]
            for line in tail:
                print(f"    {line}", flush=True)
            continue
        metrics = extract_metrics(json.loads(summary_path.read_text(encoding="utf-8")))
        print(
            f"[ablation] {index}/{len(plan)} {label} done "
            f"R@5={metrics['r_at_5']} R@10={metrics['r_at_10']} ({elapsed:.0f}s)",
            flush=True,
        )

    if not args.limit:
        rows, csv_path, md_path = aggregate()
        print(f"[ablation] aggregated {len(rows)} rows -> {csv_path}", flush=True)
        print(f"[ablation] table -> {md_path}", flush=True)
    if failed:
        print(f"[ablation] FAILED_CONFIGS: {', '.join(failed)}", flush=True)
        return 1
    print("[ablation] SWEEP_COMPLETE", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
