#!/usr/bin/env python3
"""Generate the ARR manuscript's LaTeX tables from measured CSV/JSON only.

No hand-typed numbers: baseline comparison comes from results/comparison.csv,
the ablation table from results/ablation/ablation.csv, and latencies from the
frozen full-mode summary JSONs. Output .tex files are \\input by main.tex.

Usage:
  .venv/bin/python benchmarks/comparison/make_paper_tables.py --out <dir>
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
ABLATION_CSV = RESULTS / "ablation" / "ablation.csv"
COMPARISON_CSV = RESULTS / "comparison.csv"

BENCH_ORDER = ["longmemeval", "locomo", "convomem"]
BENCH_LABEL = {"longmemeval": "LongMemEval-S", "locomo": "LoCoMo", "convomem": "ConvoMem"}
FULL_N = {"longmemeval": "500", "locomo": "1982", "convomem": "250"}

ABLATION_LABEL = {
    "enhanced_v2_boost": r"Full system (\texttt{enhanced\_v2\_boost})",
    "ablate_no_bigram": r"\quad $-$ bigram overlap boost",
    "ablate_no_keyword": r"\quad $-$ IDF keyword overlap boost",
    "ablate_no_temporal": r"\quad $-$ temporal proximity boost",
    "ablate_rrf_plain": r"RRF fusion only (all boosts off)",
    "ablate_vec_only": r"Dense retrieval only",
    "ablate_fts_only": r"Lexical (FTS5) only",
}
ABLATION_ORDER = [
    "enhanced_v2_boost", "ablate_no_bigram", "ablate_no_keyword",
    "ablate_no_temporal", "ablate_rrf_plain", "ablate_vec_only", "ablate_fts_only",
]


def read_ablation() -> dict[tuple[str, str], dict[str, str]]:
    merged: dict[tuple[str, str], dict[str, str]] = {}
    with ABLATION_CSV.open(encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            key = (row["bench"], row["mode"])
            target = merged.setdefault(key, {})
            for metric in ("r_at_5", "r_at_10", "ndcg_at_5"):
                if row.get(metric):
                    target[metric] = row[metric]
    return merged


def read_comparison() -> dict[tuple[str, str, str], dict[str, str]]:
    """(system, benchmark, top_k) -> row, keeping only full-N rows."""
    rows: dict[tuple[str, str, str], dict[str, str]] = {}
    with COMPARISON_CSV.open(encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            if row["n"] != FULL_N[row["benchmark"]]:
                continue
            rows[(row["system"], row["benchmark"], row["top_k"])] = row
    return rows


def fmt(value: str | None, digits: int = 1) -> str:
    if value in (None, ""):
        return "--"
    return f"{float(value):.{digits}f}"


def baseline_table(comparison, ablation) -> str:
    """Systems x (R@5, R@10) per bench. ERINYS numbers come from the frozen
    ablation full-mode rows (same-day, same-env as the ablation study)."""

    def erinys_cell(bench: str, metric: str) -> str:
        return fmt(ablation.get((bench, "enhanced_v2_boost"), {}).get(metric))

    def comp_cell(system: str, bench: str, metric: str) -> str:
        # comparison.csv rows carry a single cutoff each: r_at_k at top_k.
        top_k = metric.rsplit("_", 1)[1]
        row = comparison.get((system, bench, top_k))
        return fmt(row["r_at_k"]) if row else "--"

    lines = [
        "% Auto-generated by benchmarks/comparison/make_paper_tables.py — do not edit numbers by hand.",
        r"\begin{tabular}{lcccccc}",
        r"\toprule",
        r" & \multicolumn{2}{c}{LongMemEval-S} & \multicolumn{2}{c}{LoCoMo} & \multicolumn{2}{c}{ConvoMem} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
        r"System & R@5 & R@10 & R@5 & R@10 & R@5 & R@10 \\",
        r"\midrule",
    ]
    erinys = " & ".join(
        [r"\textbf{ERINYS}"]
        + [f"\\textbf{{{erinys_cell(b, m)}}}"
           for b in BENCH_ORDER for m in ("r_at_5", "r_at_10")]
    )
    lines.append(erinys + r" \\")
    for system, label in (("bm25", "BM25"), ("rag", "Naive dense RAG"), ("mem0", "Mem0 (OSS, local)")):
        cells = [comp_cell(system, b, m) for b in BENCH_ORDER for m in ("r_at_5", "r_at_10")]
        lines.append(f"{label} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def ablation_table(ablation) -> str:
    lines = [
        "% Auto-generated by benchmarks/comparison/make_paper_tables.py — do not edit numbers by hand.",
        r"\begin{tabular}{lccc}",
        r"\toprule",
        r"Configuration & LongMemEval-S & LoCoMo & ConvoMem \\",
        r" & R@5 & R@5 & R@5 \\",
        r"\midrule",
    ]
    for mode in ABLATION_ORDER:
        cells = []
        for bench in BENCH_ORDER:
            row = ablation.get((bench, mode))
            cells.append(fmt(row.get("r_at_5")) if row else "n/a")
        bold = mode == "enhanced_v2_boost"
        cells = [f"\\textbf{{{c}}}" if bold and c not in ("--", "n/a") else c for c in cells]
        lines.append(f"{ABLATION_LABEL[mode]} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def latency_report(out_dir: Path) -> None:
    """Print full-mode retrieval latency from the frozen summaries (for prose)."""
    for bench in BENCH_ORDER:
        pattern = f"ablation/{bench}_enhanced_v2_boost_k10/summary_*.json"
        hits = sorted(RESULTS.glob(pattern))
        if not hits:
            continue
        timing = json.loads(hits[-1].read_text(encoding="utf-8")).get("timing", {})
        print(f"  latency[{bench}]: {timing}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, help="output dir for .tex files")
    args = parser.parse_args()
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    ablation = read_ablation()
    comparison = read_comparison()

    (out_dir / "baseline_comparison.tex").write_text(
        baseline_table(comparison, ablation), encoding="utf-8")
    (out_dir / "ablation.tex").write_text(ablation_table(ablation), encoding="utf-8")
    print(f"wrote {out_dir}/baseline_comparison.tex")
    print(f"wrote {out_dir}/ablation.tex")
    latency_report(out_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
